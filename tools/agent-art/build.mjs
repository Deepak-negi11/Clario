import { readFileSync, writeFileSync } from "node:fs";
import { fileURLToPath } from "node:url";
const out = fileURLToPath(
  new URL("../../apps/web/public/assets/agents/", import.meta.url),
);
// Original companion illustrations. The Cursor mark itself is the unmodified official 2.5D asset.
const motion = `<style>@keyframes hover{0%,100%{transform:translateY(0)}50%{transform:translateY(-2px)}}@keyframes blink{0%,43%,47%,100%{transform:scaleY(1)}45%{transform:scaleY(.08)}}@keyframes tap{0%,100%{transform:translateY(0)}50%{transform:translateY(2px)}}.float{animation:hover 3.4s ease-in-out infinite;transform-origin:48px 46px}.eyes{animation:blink 5.4s linear infinite;transform-origin:48px 42px}.working .float{animation-duration:1.8s}.working .left{animation:tap .5s ease-in-out infinite}.working .right{animation:tap .5s ease-in-out -.25s infinite}.working .cursor{animation:blink 1.3s steps(1) infinite;transform-origin:64px 50px}@media(prefers-reduced-motion:reduce){*{animation:none!important}}</style>`;
const defs = `<defs><linearGradient id="clay" x1="0" y1="0" x2=".8" y2="1"><stop stop-color="#e99875"/><stop offset=".55" stop-color="#d67b58"/><stop offset="1" stop-color="#bf5c3e"/></linearGradient><linearGradient id="shell" x1="0" y1="0" x2="1" y2="1"><stop stop-color="#3d4d50"/><stop offset="1" stop-color="#162629"/></linearGradient><linearGradient id="rim" x1="0" y1="0" x2="0" y2="1"><stop stop-color="#667b7c"/><stop offset="1" stop-color="#33494b"/></linearGradient><linearGradient id="glass" x1="0" y1="0" x2="1" y2="1"><stop stop-color="#fefefd"/><stop offset="1" stop-color="#dcdfe0"/></linearGradient></defs>`;
const shadow = `<ellipse cx="48" cy="80" rx="29" ry="4" fill="#29322e" opacity=".1"/>`;
const claude = `<g class="float"><g fill="#b65d40"><path class="left" d="M28 62h7v14h-7zM48 62h7v14h-7z"/><path class="right" d="M39 62h6v12h-6zM60 62h7v12h-7z"/></g><path d="M23 25h48v9h12v17H71v13H23V51H11V34h12z" fill="url(#clay)"/><path d="M23 25h48v3H26v33h-3V51H11v-3h12z" fill="#f4b697" opacity=".75"/><path d="M71 34h12v17H71v13H23v-4h44V31h4z" fill="#a84d34" opacity=".24"/><g class="eyes" fill="#281d18"><rect x="32" y="35" width="6" height="13" rx=".8"/><rect x="56" y="35" width="6" height="13" rx=".8"/></g><path d="M14 35h7v2h-7zM73 35h7v2h-7z" fill="#f1b08e" opacity=".5"/></g>`;
// Embed the transparent pet so SVG image documents make no nested external request.
const codex = `<g class="float"><image href="data:image/png;base64,${readFileSync(out + "codex-pet.png").toString("base64")}" x="10" y="4" width="76" height="82"/></g>`;
const cursor = `<g class="float"><ellipse cx="49" cy="71" rx="22" ry="4" fill="#242930" opacity=".08"/><image href="cursor-mark.svg" x="17" y="10" width="62" height="65"/></g>`;
// SVG image documents cannot load external nested SVGs. Embed the official paths directly.
const official = readFileSync(out + "cursor-mark.svg", "utf8");
const svgView = official.match(/viewBox="([^"]+)"/)?.[1] ?? "0 0 100 100";
const inner = official
  .replace(/^[\s\S]*?<svg[^>]*>/, "")
  .replace(/<\/svg>\s*$/, "");
const cursorEmbedded = cursor.replace(
  /<image[^>]+\/>/,
  `<svg x="17" y="10" width="62" height="65" viewBox="${svgView}">${inner}</svg>`,
);
const generic = `<g class="float"><rect x="18" y="22" width="60" height="45" rx="14" fill="url(#glass)" stroke="#a9b6b0"/><path d="m36 37-8 8 8 8m24-16 8 8-8 8" fill="none" stroke="#5c756c" stroke-width="3" stroke-linecap="round" stroke-linejoin="round"/><path d="m51 36-6 18" stroke="#5c756c" stroke-width="3" stroke-linecap="round"/></g>`;
for (const [name, art] of Object.entries({
  claude,
  codex,
  cursor: cursorEmbedded,
  agent: generic,
}))
  for (const working of [false, true]) {
    const svg = `<svg xmlns="http://www.w3.org/2000/svg" width="96" height="96" viewBox="0 0 96 96" class="${working ? "working" : "idle"}">${defs}${motion}${shadow}${art}</svg>`;
    writeFileSync(
      out + name + (working ? "-working" : "") + ".svg",
      svg + "\n",
    );
  }

// Share the unchanged official paths with the native WebGL mesh builder.
writeFileSync(
  new URL("../../apps/web/lib/agents/cursor-mark.ts", import.meta.url),
  `// Generated by tools/agent-art/build.mjs from cursor-mark.svg.\nexport const CURSOR_MARK_SVG = ${JSON.stringify(official)};\n`,
);
